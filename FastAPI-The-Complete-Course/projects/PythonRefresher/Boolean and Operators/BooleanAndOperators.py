"""
Boolean and Operators
"""

# Comparison Operators
print(1 == 2)
print(2 == 2)
print(1 != 2)
print(1 > 2)
print(1 < 2)
print(1 >= 1)
print(1 <= 2)


# Logical Operators
print(1 > 3 and 5 < 7)  # false if any one is false
print(1 > 3 or 5 < 7)   # true if any one is true
print(not(1 == 1))  # 1 == 1 is true, not() reverse it to false
print(not(1 == 2))  # 1 == 2 is false, not() reverse it to true


